-- ExamenMate · „🎯 PREGĂTEȘTE-MĂ DE EXAMEN" — testul zilei + fluxul Arenei
-- (8 noiembrie 2026)
--
-- Cererea: un buton „pregătește-mă de examen" care amintește zilnic, printr-o
-- notificare, să rezolvi un test; progresul cu XP în Arena și clasament, simplu,
-- cu promovare și alte răsplăți; contează și o parte de test;
-- în Arena, ca pe Facebook, cine a rezolvat, cine a promovat, ce subiect, ce
-- provocări noi apar — fără note.
--
--   daily_tests                 — un rând pe elev pe zi: examenul, testul zilei,
--                                 câte exerciții a lucrat azi, starea (deschis /
--                                 lucrat), recompensa
--   arena_feed                  — activitatea din Arenă (cine a lucrat la testul
--                                 zilei, a promovat, are o serie, a primit o
--                                 insignă; turnee și provocări noi). Se citește
--                                 DOAR prin API (prenumele + inițiala, fără note)
--   user_stats.prep_exam        — examenul ales (evaluare-nationala, bac-mate-info,
--                                 bac-stiinte, bac-tehnologic)
--   user_stats.prep_format      — 'interactiv' | 'pdf' (testul zilei)
--   user_stats.prep_notify…     — amintirea zilnică a testului (ca la misiune)
--   user_stats.arena_public     — false = elevul nu apare în fluxul Arenei
--
-- Scrie doar serverul (api/gamificare.js, api/ai-score.js, api/rezolva-pdf.js,
-- api/ai-correct.js — rolul de serviciu). Elevul își poate citi doar rândurile
-- lui din daily_tests; fluxul nu se citește direct din browser.
-- Rulează DUPĂ gamificare_v2.sql și misiune_notificari.sql, în Supabase → SQL
-- Editor → New Query → Run. Idempotent: se poate rula de mai multe ori.
-- =====================================================================

-- ─── 1. Testul fiecărei zile ─────────────────────────────────────────────────
create table if not exists public.daily_tests (
  id            uuid primary key default gen_random_uuid(),
  user_id       uuid not null references auth.users(id) on delete cascade,
  day           date not null,                          -- ziua (Europa/București)
  exam          text not null,                          -- evaluare-nationala | bac-mate-info | bac-stiinte | bac-tehnologic
  content_id    uuid references public.content(id) on delete set null,
  content_title text,                                   -- titlul, păstrat și dacă testul se șterge
  content_type  text,                                   -- interactive | pdf
  status        text not null default 'deschis'
                check (status in ('deschis', 'lucrat')),
  items_done    integer not null default 0,             -- cele mai multe exerciții lucrate azi într-un test
  best_pct      integer,                                -- cel mai bun procent de azi
  grade         numeric(4,2),                           -- nota (privată: o vede doar elevul)
  worked_on     text,                                   -- unde a lucrat azi (ex. „Subiectul I")
  xp            integer not null default 0,             -- recompensa zilei (XP)
  created_at    timestamptz not null default now(),
  done_at       timestamptz,
  unique (user_id, day)
);
alter table public.daily_tests enable row level security;

grant select, insert, update, delete on public.daily_tests to authenticated;
grant select, insert, update, delete on public.daily_tests to service_role;

create index if not exists idx_daily_tests_user_day on public.daily_tests(user_id, day desc);
create index if not exists idx_daily_tests_day_status on public.daily_tests(day, status);

do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'daily_tests' and policyname = 'daily_tests_service') then
    create policy daily_tests_service on public.daily_tests for all to service_role
      using (true) with check (true);
  end if;
  -- elevul își vede doar zilele lui; scrie DOAR serverul (fără insert/update de pe client)
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'daily_tests' and policyname = 'daily_tests_own_select') then
    create policy daily_tests_own_select on public.daily_tests for select to authenticated
      using (user_id = (select auth.uid()));
  end if;
end $$;

-- ─── 2. Fluxul de activitate al Arenei ───────────────────────────────────────
-- Fără note și fără numele complet: API-ul (api/_lib/arenaFeed.js) arată
-- prenumele și inițiala („Ana P."), ca în clasamentul ligii, și sare peste
-- elevii care au ales să nu apară (user_stats.arena_public = false).
create table if not exists public.arena_feed (
  id          bigint generated by default as identity primary key,
  user_id     uuid references auth.users(id) on delete cascade,   -- NULL = anunț al Arenei (turneu nou, provocarea zilei)
  kind        text not null,                                       -- test | serie | promovare | insigna | nivel | turneu | provocare | duel
  payload     jsonb not null default '{}'::jsonb,                  -- detaliile (examenul, subiectul, liga…) — niciodată nota
  dedupe_key  text,                                                -- un singur rând per cheie (ex. „test:<user>:<zi>")
  created_at  timestamptz not null default now()
);
alter table public.arena_feed enable row level security;

grant select, insert, update, delete on public.arena_feed to authenticated;
grant select, insert, update, delete on public.arena_feed to service_role;

create index if not exists idx_arena_feed_created on public.arena_feed(created_at desc);
create unique index if not exists uq_arena_feed_dedupe on public.arena_feed(dedupe_key) where dedupe_key is not null;

do $$
begin
  -- doar serverul citește și scrie (fluxul ajunge la elevi prin API, cu numele scurtate);
  -- fără politici pentru `authenticated` = niciun rând citit direct din browser
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'arena_feed' and policyname = 'arena_feed_service') then
    create policy arena_feed_service on public.arena_feed for all to service_role
      using (true) with check (true);
  end if;
end $$;

-- ─── 3. Preferințele elevului, în user_stats ─────────────────────────────────
alter table public.user_stats add column if not exists prep_exam text;
alter table public.user_stats add column if not exists prep_format text;
alter table public.user_stats add column if not exists prep_notify boolean;
alter table public.user_stats add column if not exists prep_notify_hour smallint not null default 18;
alter table public.user_stats add column if not exists prep_notified_on date;
alter table public.user_stats add column if not exists prep_streak_notified_on date;
alter table public.user_stats add column if not exists arena_public boolean not null default true;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'user_stats_prep_notify_hour_chk') then
    alter table public.user_stats add constraint user_stats_prep_notify_hour_chk
      check (prep_notify_hour between 0 and 23);
  end if;
  if not exists (select 1 from pg_constraint where conname = 'user_stats_prep_format_chk') then
    alter table public.user_stats add constraint user_stats_prep_format_chk
      check (prep_format is null or prep_format in ('interactiv', 'pdf'));
  end if;
end $$;

comment on column public.user_stats.prep_exam is
  'Pregătește-mă de examen: examenul ales (evaluare-nationala, bac-mate-info, bac-stiinte, bac-tehnologic). NULL = încă nealeasă.';
comment on column public.user_stats.prep_format is
  'Pregătește-mă de examen: testul zilei interactiv sau pe PDF (subiecte oficiale, Premium). NULL = automat.';
comment on column public.user_stats.prep_notify is
  'Amintirea zilnică a testului: true = pornită, false = oprită, NULL = încă nealeasă.';
comment on column public.user_stats.prep_notify_hour is
  'Ora amintirii testului zilei (ora României, 8–21).';
comment on column public.user_stats.arena_public is
  'false = elevul nu apare în fluxul de activitate al Arenei (prenume + inițială, fără note).';

-- cronul de la fiecare oră citește doar elevii cu amintirea pornită
create index if not exists idx_user_stats_prep_notify
  on public.user_stats(prep_notify_hour) where prep_notify is true;

